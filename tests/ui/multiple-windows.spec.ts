import path from 'node:path'
import { promises as fs } from 'node:fs'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { test, expect, openTask } from './fixtures'
import { createProject } from '../../src/core/workspace'

test('새 창과 재실행으로 여러 창을 열고 같은 프로젝트의 상태를 공유한다', async ({ orbit }) => {
  const opened = orbit.app.waitForEvent('window')
  await orbit.page.getByRole('button', { name: '새 창', exact: true }).click()
  const second = await opened
  await second.waitForLoadState()
  await expect(second.getByRole('button', { name: '프로젝트 폴더 열기', exact: true })).toBeVisible()
  await second.evaluate((dir) => window.orbit.invoke('openProject', dir), orbit.ctx.projectDir)
  await second.reload(); await expect(second.locator('.brand-name')).toContainText('Markdown UI QA')
  await second.evaluate(() => window.orbit.invoke('createTask', { title: '두 창 공유 문서', type: 'research', horizon: '지금' }))
  await orbit.page.locator('nav').getByRole('button', { name: '할 일', exact: true }).click()
  await expect(orbit.page.getByText('두 창 공유 문서', { exact: true })).toBeVisible()
  await second.getByRole('button', { name: '프로젝트 닫기', exact: true }).click()
  await expect(orbit.page.getByText('두 창 공유 문서', { exact: true })).toBeVisible()
  const reopening = orbit.app.waitForEvent('window')
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const executable = await orbit.app.evaluate(() => process.execPath)
  await promisify(execFile)(executable, [path.join(orbit.directory, 'launch.cjs'), '--no-sandbox'], { env, windowsHide: true, timeout: 15000 })
  const third = await reopening; await third.waitForLoadState()
  await expect(third.getByRole('button', { name: '프로젝트 폴더 열기', exact: true })).toBeVisible()
  await third.close(); await second.close()
})

test('서로 다른 창의 문서 이미지를 격리하고 닫았다 다시 연 창의 화면 설정을 보존한다', async ({ orbit }) => {
  const other = await createProject(path.join(orbit.directory, 'images'), '두 번째 이미지 프로젝트')
  for (const [ctx, width] of [[orbit.ctx, 40], [other, 90]] as const) await fs.writeFile(path.join(ctx.dataRoot, 'probe.svg'), `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="30"><rect width="${width}" height="30"/></svg>`)
  const opening = orbit.app.waitForEvent('window'); await orbit.page.getByRole('button', { name: '새 창', exact: true }).click()
  const second = await opening; await second.waitForLoadState()
  await second.evaluate((dir) => window.orbit.invoke('openProject', dir), other.projectDir)
  const firstDoc = await openTask(orbit, '![창 이미지](../probe.svg)')
  const secondDoc = await openTask({ ...orbit, page: second, ctx: other }, '![창 이미지](../probe.svg)')
  await expect.poll(() => firstDoc.editor.getByAltText('창 이미지').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(40)
  await expect.poll(() => secondDoc.editor.getByAltText('창 이미지').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(90)
  await second.locator('.modal').getByRole('button', { name: '취소', exact: true }).click()
  await second.locator('nav').getByRole('button', { name: '계정·사용량', exact: true }).click(); await second.close()
  await orbit.page.locator('.modal').getByRole('button', { name: '취소', exact: true }).click()
  const reopening = orbit.app.waitForEvent('window'); await orbit.page.getByRole('button', { name: '새 창', exact: true }).click()
  const reopened = await reopening; await reopened.waitForLoadState()
  await reopened.evaluate((dir) => window.orbit.invoke('openProject', dir), other.projectDir); await reopened.reload()
  await expect(reopened.getByRole('heading', { name: '계정·사용량', exact: true })).toBeVisible()
  await reopened.close()
})

test('서로 다른 프로젝트를 열고 계정 전환은 창 전체와 새 실행에 즉시 반영한다', async ({ orbit }) => {
  const other = await createProject(path.join(orbit.directory, 'other'), '다른 프로젝트')
  const opening = orbit.app.waitForEvent('window')
  await orbit.page.keyboard.press('ControlOrMeta+Shift+n')
  const second = await opening; await second.waitForLoadState()
  await second.evaluate((dir) => window.orbit.invoke('openProject', dir), other.projectDir); await second.reload()
  await expect(second.locator('.brand-name')).toContainText('다른 프로젝트')
  await expect(orbit.page.locator('.brand-name')).toContainText('Markdown UI QA')
  await orbit.page.locator('nav').getByRole('button', { name: '계정·사용량', exact: true }).click()
  await orbit.page.getByRole('button', { name: '계정 등록', exact: true }).click()
  await orbit.page.getByLabel('제공자', { exact: true }).selectOption('codex')
  await orbit.page.getByLabel('계정 이름', { exact: true }).fill('추가 Codex')
  await orbit.page.getByRole('button', { name: '계정 저장', exact: true }).click()
  await orbit.page.getByLabel('Codex 현재 계정', { exact: true }).selectOption({ label: '추가 Codex' })
  await expect(second.getByLabel('Codex 현재 계정', { exact: true }).locator('option:checked')).toHaveText('추가 Codex')
  await expect(orbit.page.getByRole('article', { name: '추가 Codex', exact: true })).toContainText('현재 선택')
  await second.reload()
  await expect(second.getByLabel('Codex 현재 계정', { exact: true }).locator('option:checked')).toHaveText('추가 Codex')
  await orbit.page.evaluate(() => window.orbit.invoke('savePipeline', { title: '계정 선택 검증', nodes: [{ id: 'start', kind: 'start', terminal: 'new', text: '' }, { id: 'print', kind: 'print', terminal: 'new', text: '출력' }], edges: [{ from: 'start', to: 'print' }] }))
  await orbit.page.locator('nav').getByRole('button', { name: '자동화', exact: true }).click()
  await orbit.page.locator('.automation-page > .row .seg').getByRole('button', { name: '예약', exact: true }).click()
  await orbit.page.getByRole('button', { name: '새 예약', exact: true }).click()
  await expect(orbit.page.getByLabel('Codex 실행 계정', { exact: true }).locator('option:checked')).toHaveText('추가 Codex')
  await second.getByLabel('Codex 현재 계정', { exact: true }).selectOption('default-codex')
  await expect(orbit.page.getByLabel('Codex 실행 계정', { exact: true })).toHaveValue('default-codex')
  await orbit.page.getByLabel('Codex 실행 계정', { exact: true }).selectOption({ label: '추가 Codex' })
  await second.getByLabel('Codex 현재 계정', { exact: true }).selectOption({ label: '추가 Codex' })
  await second.getByLabel('Codex 현재 계정', { exact: true }).selectOption('default-codex')
  await expect(orbit.page.getByLabel('Codex 실행 계정', { exact: true }).locator('option:checked')).toHaveText('추가 Codex')
  await second.getByRole('button', { name: '프로젝트 닫기', exact: true }).click()
  await expect(orbit.page.locator('.brand-name')).toContainText('Markdown UI QA')
  await second.close()
})
